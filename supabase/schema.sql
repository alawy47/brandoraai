-- BRANDORA database schema for Supabase (Postgres).
-- Run in the Supabase SQL editor, or save as a migration with the Supabase CLI.

create table if not exists public.projects (
  id          text primary key,                 -- generated by the app (e.g. brand_lx3k9a2)
  user_id     uuid not null references auth.users (id) on delete cascade,
  name        text not null,
  input       jsonb not null,                   -- the brief form answers
  concepts    jsonb not null,                   -- three concepts incl. palette, fonts, selected logo and logo concepts
  brief       jsonb,                            -- creative brief
  selected    smallint not null default 0,
  status      text not null default 'progress' check (status in ('progress', 'completed')),
  favorite    boolean not null default false,
  seed        bigint,
  meta        jsonb not null default '{}',      -- workflow progress (visited steps, exported)
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists projects_user_updated_idx on public.projects (user_id, updated_at desc);

alter table public.projects enable row level security;
drop policy if exists "read own projects" on public.projects;
drop policy if exists "insert own projects" on public.projects;
drop policy if exists "update own projects" on public.projects;
drop policy if exists "delete own projects" on public.projects;
create policy "read own projects"   on public.projects for select using (auth.uid() = user_id);
create policy "insert own projects" on public.projects for insert with check (auth.uid() = user_id);
create policy "update own projects" on public.projects for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "delete own projects" on public.projects for delete using (auth.uid() = user_id);

-- Provider usage, written by the API server with the service role key (never from the browser).
create table if not exists public.api_usage (
  id          bigint generated always as identity primary key,
  created_at  timestamptz not null default now(),
  provider    text not null,
  task        text not null,
  model       text,
  ok          boolean not null,
  ms          integer,
  cost_usd    numeric(10, 5),
  error       text
);
alter table public.api_usage enable row level security; -- no policies: only the service role can read or write

-- Private bucket for exported packages (files under <user_id>/...).
insert into storage.buckets (id, name, public) values ('exports', 'exports', false) on conflict do nothing;
drop policy if exists "users manage own exports" on storage.objects;
create policy "users manage own exports" on storage.objects for all
  using (bucket_id = 'exports' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'exports' and (storage.foldername(name))[1] = auth.uid()::text);
